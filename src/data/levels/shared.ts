/** 取某个发送者的头像；未知发送者回退到首字 + 灰调。 */
export function avatarFor(name: string): { text: string; tone: AvatarTone } {
  const hit = SENDER_AVATARS[name]
  if (hit) return hit
  return { text: name.slice(0, 1) || '?', tone: 'slate' }
}

